export function getCurrencyDisplayName(currency: string): string {
  const mainCurrency = currency.split('&')[0].replace(/\s*\([^)]*\)/g, '').trim();
  const normalized = mainCurrency.toLocaleLowerCase();
  const denomination = currencyDenominations.find((name) =>
    normalized.endsWith(name.toLocaleLowerCase())
  );

  return denomination ?? mainCurrency;
}
